def main() -> int:
    db = SessionLocal()
    try:
        lessons = db.query(Lesson).all()
        log.info("Found %d lessons in DB", len(lessons))

        added = skipped_existing = unmatched = 0
        unknown_titles: list[str] = []

        for lesson in lessons:
            prompts = QUESTIONS_BY_TITLE.get(lesson.title_kk)
            if not prompts:
                unmatched += 1
                unknown_titles.append(lesson.title_kk)
                continue

            existing_question = (
                db.query(LessonBlock)
                .filter(
                    LessonBlock.lesson_id == lesson.id,
                    LessonBlock.type == "question",
                )
                .first()
            )
            if existing_question:
                skipped_existing += 1
                log.info("  [skip] %s — already has question block", lesson.title_kk)
                continue

            max_pos = (
                db.query(LessonBlock.position)
                .filter(LessonBlock.lesson_id == lesson.id)
                .order_by(LessonBlock.position.desc())
                .first()
            )
            next_pos = (max_pos[0] + 1) if max_pos else 0

            db.add(
                LessonBlock(
                    lesson_id=lesson.id,
                    position=next_pos,
                    type="question",
                    payload={
                        "title_kk": QUESTION_TITLE,
                        "questions_kk": list(prompts),
                    },
                )
            )
            added += 1
            log.info("  [add ] %s — %d questions appended", lesson.title_kk, len(prompts))

        db.commit()

        log.info("")
        log.info("Done. added=%d skipped=%d unmatched=%d", added, skipped_existing, unmatched)
        if unknown_titles:
            log.info("Lessons without a prepared question set:")
            for t in unknown_titles:
                log.info("  - %s", t)
        return 0
    except Exception:
        db.rollback()
        log.exception("Migration failed; rolled back")
        return 1
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())
